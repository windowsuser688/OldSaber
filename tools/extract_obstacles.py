"""Extract the 0.10.1 obstacle hierarchy, meshes/materials and procedural sizing code."""
import base64,json
from pathlib import Path
import UnityPy
from UnityPy.classes.PPtr import PPtr
from UnityPy.helpers.MeshHelper import MeshHandler
from extract_classic import ClassicTypeTreeGenerator,json_value
root=Path(__file__).resolve().parent.parent
out=root/'extracted/OldSaberObstacles';out.mkdir(parents=True,exist_ok=True)
e=UnityPy.load(str(root/'Beat Saber_Data/sharedassets4.assets'))
g=ClassicTypeTreeGenerator('2017.4.1f1');g.load_local_dll_folder(str(root/'Beat Saber_Data/Managed'));e.typetree_generator=g
builtin=UnityPy.load(str(root/'Beat Saber_Data/Resources/unity default resources'));bi={o.path_id:o for o in builtin.objects}
def ref(o,p):
 if p['m_FileID'] and 'unity default resources' in o.assets_file.externals[p['m_FileID']-1].path:return bi[p['m_PathID']]
 return PPtr(**p,assetsfile=o.assets_file).deref()
def key(o):return Path(o.assets_file.name).name+'__'+str(o.path_id)
def tree(o):return o.read_typetree()
def save(o):
 k=key(o);(out/(k+'.json')).write_text(json.dumps(tree(o),default=json_value,indent=2));(out/(k+'.bin')).write_bytes(o.get_raw_data());return k
D={'version':'0.10.1','prefab':'ObstacleFull','nodes':[],'meshes':{},'materials':{},'textures':{},'bindings':{}}
def mesh(o):
 k=save(o)
 if k not in D['meshes']:
  h=MeshHandler(o.read());h.process();D['meshes'][k]={n:[list(v[:s]) for v in vs] if vs else [] for n,vs,s in [('vertices',h.m_Vertices,3),('normals',h.m_Normals,3),('uv',h.m_UV0,2),('uv2',h.m_UV1,2),('tangents',h.m_Tangents,4),('colors',h.m_Colors,4)]};D['meshes'][k]['triangles']=[[i for tri in sub for i in tri] for sub in h.get_triangles()]
 return k
def mat(o):
 k=save(o)
 if k not in D['materials']:
  t=tree(o);m={'name':t['m_Name'],'floats':dict(t['m_SavedProperties']['m_Floats']),'colors':dict(t['m_SavedProperties']['m_Colors']),'textures':{}};D['materials'][k]=m
  shader=ref(o,t['m_Shader']);save(shader)
  for name,p in t['m_SavedProperties']['m_TexEnvs']:
   if not p['m_Texture']['m_PathID']:continue
   tex=ref(o,p['m_Texture']);tk=save(tex);path=out/(tk+'.png');tex.read().image.save(path);D['textures'][tk]=base64.b64encode(path.read_bytes()).decode();m['textures'][name]={'id':tk,'scale':p['m_Scale'],'offset':p['m_Offset']}
 return k
def walk(tr,parent=None):
 t=tree(tr);go=ref(tr,t['m_GameObject']);gt=tree(go);save(go);save(tr)
 n={'id':key(tr),'parent':parent,'name':gt['m_Name'],'active':bool(gt['m_IsActive']),'position':t['m_LocalPosition'],'rotation':t['m_LocalRotation'],'scale':t['m_LocalScale']};D['nodes'].append(n)
 for p in gt['m_Component']:
  c=ref(go,p['component']);ct=tree(c)
  if c.type.name=='MeshFilter' and ct['m_Mesh']['m_PathID']:n['mesh']=mesh(ref(c,ct['m_Mesh']))
  if c.type.name=='MeshRenderer':n['materials']=[mat(ref(c,p)) for p in ct['m_Materials']]
  if c.type.name=='MonoBehaviour':
   name=c.parse_monobehaviour_head().m_Script.deref().read().m_ClassName
   if name=='StretchableCube':n['proceduralCube']=True
   if name=='StretchableObstacle':
    for field,p in ct.items():
     if not field.startswith('_'):continue
     obj=ref(c,p)
     if obj.type.name=='MonoBehaviour':
      go2=ref(obj,tree(obj)['m_GameObject']);obj=next(ref(go2,x['component']) for x in tree(go2)['m_Component'] if ref(go2,x['component']).type.name=='Transform')
     D['bindings'][field]=key(obj)
 for p in t['m_Children']:walk(ref(tr,p),key(tr))
go=next(o for o in e.objects if o.type.name=='GameObject' and o.path_id==119)
tr=next(ref(go,p['component']) for p in tree(go)['m_Component'] if ref(go,p['component']).type.name=='Transform');walk(tr)
(root/'OldSaber/Assets/ClassicObstacles.json').write_text(json.dumps(D,separators=(',',':')))
source=(root/'extracted/classic-code/Assembly-CSharp.decompiled.cs').read_text()
start=source.index('public class StretchableCube :');end=source.index('[DisallowMultipleComponent]',start)
code=source[start:end].replace('StretchableCube','ClassicObstacleCube').replace('StretchableObstacle','ClassicObstacleGeometry')
code=code.replace('private void Awake()', 'private void OnDestroy() { if (_mesh) Destroy(_mesh); }\n\tprivate void Awake()')
(root/'OldSaber/ClassicObstacleGeometry.cs').write_text('// Geometry routines extracted from supplied 0.10.1 Assembly-CSharp.\n#pragma warning disable 0649 // Assigned from extracted bindings via reflection.\nusing UnityEngine;\nnamespace OldSaber\n{\n'+code+'\n}\n')
(out/'README.md').write_text('Extracted from supplied Beat Saber 0.10.1 sharedassets4.assets ObstacleFull/StretchableObstacle. Frame/corner meshes reference the original built-in cube. Core meshes are generated by StretchableCube; its original geometry and UV sizing code is ported to ClassicObstacleGeometry.cs. Materials, noise texture and shader bytes are archived here; runtime adapts materials to current rendering shaders. No original gameplay/collision scripts are loaded.\n')
print('Extracted',len(D['nodes']),'nodes,',len(D['meshes']),'meshes,',len(D['materials']),'materials,',len(D['textures']),'textures')
