"""Port the recovered 0.10.1 XWeaponTrail algorithm with managed renderer ownership."""
from pathlib import Path
root=Path(__file__).resolve().parent.parent
source=(root/'extracted/classic-code/Assembly-CSharp.decompiled.cs').read_text()
s=source[source.index('namespace Xft\n'):source.index('public class XWeaponTrailRenderer :')]
s=s.replace('namespace Xft','namespace OldSaber.LegacyTrail')
s=s.replace('\t\t[SerializeField]\n\t\tprivate XWeaponTrailRenderer _trailRendererPrefab;\n', '')
needle='\t\tprivate void Start()\n'
init='''        internal void Initialize(Transform start, Transform end, int frames, int segments, int skip, Color color, Material material)
        {
            PointStart=start;PointEnd=end;MaxFrame=frames;Granularity=segments;
            _skipFirstFrames=skip;MyColor=color;MyMaterial=material;
        }
'''
s=s.replace(needle,init+needle)
s=s.replace('_trailRenderer = UnityEngine.Object.Instantiate(_trailRendererPrefab, Vector3.zero, Quaternion.identity);', '''var rendererObject=new GameObject("OldSaber.ClassicTrail");
            UnityEngine.SceneManagement.SceneManager.MoveGameObjectToScene(rendererObject,gameObject.scene);
            _trailRenderer=rendererObject.AddComponent<XWeaponTrailRenderer>();
            _trailRenderer.Initialize(MyMaterial,gameObject.layer);''')
# Pool the old snapshots when a saber is disabled/re-enabled, rather than leaking pool entries.
s=s.replace('_snapshotList.Clear();','foreach(var entry in _snapshotList)_elemPool.Release(entry);\n                _snapshotList.Clear();')
s=s.replace('private XWeaponTrailRenderer _trailRendererPrefab;', 'private XWeaponTrailRenderer _unusedPrefab;')
s+='''
namespace OldSaber.LegacyTrail
{
    public sealed class XWeaponTrailRenderer : MonoBehaviour
    {
        private MeshRenderer rendererComponent;
        private Mesh ownedMesh;
        public Mesh mesh=>ownedMesh;
        internal void Initialize(Material material,int layer)
        {
            gameObject.layer=layer;
            ownedMesh=new Mesh {name="OldSaber.ClassicTrail"};ownedMesh.MarkDynamic();
            gameObject.AddComponent<MeshFilter>().sharedMesh=ownedMesh;
            rendererComponent=gameObject.AddComponent<MeshRenderer>();
            rendererComponent.sharedMaterial=material;
            rendererComponent.shadowCastingMode=UnityEngine.Rendering.ShadowCastingMode.Off;
            rendererComponent.receiveShadows=false;
        }
        private void OnEnable(){if(rendererComponent)rendererComponent.enabled=true;}
        private void OnDisable(){if(rendererComponent)rendererComponent.enabled=false;}
        private void OnDestroy(){if(ownedMesh)Destroy(ownedMesh);}
    }
}
'''
(root/'OldSaber/ClassicSaberTrail.cs').write_text('// Ported from the supplied 0.10.1 Xft trail code. Generated by tools/port_saber_trail.py.\nusing System;\nusing System.Collections.Generic;\nusing UnityEngine;\n'+s)
print('Ported original spline, snapshot history, UVs, vertex colors and trail topology')
